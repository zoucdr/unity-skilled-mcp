/**
 * 搭建阶段 —— 按 UI Spec 在 Unity 当前场景里建真实 UGUI 层级。
 *
 * 主路径 code：用 code.execute 一次性生成完整层级，能建真 Slider / Toggle / InputField /
 *              ScrollRect / Dropdown 并绑定 fillRect、handleRect、graphic、textComponent、
 *              placeholder、content、viewport、targetGraphic 等序列化引用。
 * 降级路径 module：ugui.create_component（控件残缺，verify 会如实报出来）。
 *
 * 为什么主路径不直接用 demo 的 ugui.create_component：
 *  1) UguiToolModule.cs:72 的 [ToolAction] 只声明 component/name，但 handler 读 parent/x/y/w/h/
 *     label/value —— 参数被 schema 吞掉，外部传不进去（实测 ToolCatalog.cs:140-170）。
 *  2) UguiToolkit.cs Slider 用两张 Filled Image 假扮、InputField 没绑 textComponent/placeholder、
 *     Toggle 没绑 graphic，且没有 ScrollRect / Dropdown。
 *  3) 静态 map 依赖「同一会话内已创建」，域重载即失效。
 *
 * 生成的 C# 全部是语句片段（mode=runtime），C#5 兼容：无插值/?./nameof/out var/局部函数，
 * 无裸 return;（mcp.js lintCSharp 会拦），数据用 C# 字面量注入（工程无 SimpleJson）。
 */
'use strict';

const mcp = require('./mcp');
const coords = require('./coords');
const controls = require('./controls');

/** #RRGGBB / #RRGGBBAA → C# new Color(...) 字面量。 */
function csColor(hex, fallback = '#FFFFFFFF') {
  let s = (hex || fallback).replace('#', '');
  if (s.length === 3) s = s.split('').map(c => c + c).join('');
  if (s.length === 6) s += 'FF';
  if (s.length !== 8) s = 'FFFFFFFF';
  const v = [0, 2, 4, 6].map(i => parseInt(s.substr(i, 2), 16) / 255);
  return `new UnityEngine.Color(${v[0].toFixed(3)}f, ${v[1].toFixed(3)}f, ${v[2].toFixed(3)}f, ${v[3].toFixed(3)}f)`;
}

/** 文本对齐 → UnityEngine.TextAnchor 枚举名。 */
const TEXT_ANCHORS = {
  upper_left: 'UpperLeft', upper_center: 'UpperCenter', upper_right: 'UpperRight',
  middle_left: 'MiddleLeft', middle_center: 'MiddleCenter', middle_right: 'MiddleRight',
  lower_left: 'LowerLeft', lower_center: 'LowerCenter', lower_right: 'LowerRight',
  left: 'MiddleLeft', center: 'MiddleCenter', right: 'MiddleRight',
};

function csArray(a) { return `new float[] { ${a.map(x => Number(x).toFixed(3) + 'f').join(', ')} }`; }
function q(s) { return String(s === undefined || s === null ? '' : s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, '\\n'); }

/** 节点 → RectTransform 布局数组（coords.toUGUI 是唯一来源）。 */
function rectValues(node, spec) {
  const u = coords.toUGUI(node, spec);
  return [
    ...u.anchorMin, ...u.anchorMax, ...u.pivot, ...u.anchoredPosition, ...u.sizeDelta,
    u.stretch ? 1 : 0,
    u.offsetMin ? u.offsetMin[0] : 0, u.offsetMin ? u.offsetMin[1] : 0,
    u.offsetMax ? u.offsetMax[0] : 0, u.offsetMax ? u.offsetMax[1] : 0,
  ];
}

function spriteFor(node, manifest) {
  const it = (manifest && manifest.items || []).find(x => x.id === node.id);
  return it || null;
}

/**
 * 生成 C# 语句片段。
 * @param {object} spec 归一化 Spec
 * @param {object} manifest assets_manifest.json
 * @param {object} o { project, rootName, saveScene }
 */
function generateCSharp(spec, manifest, o = {}) {
  const project = o.project || mcp.resolveProject();
  const rootName = o.rootName || `UGUI_${spec.name.replace(/[^A-Za-z0-9_]/g, '_')}`;
  const relOf = id => {
    const it = (manifest && manifest.items || []).find(x => x.id === id);
    if (!it) return null;
    return require('./assets').toAssetRel(it.path, project);
  };
  const stateRel = (node, state) => {
    const it = (manifest && manifest.items || []).find(x => x.id === node.id);
    if (!it || !it.states || !it.states[state]) return null;
    return require('./assets').toAssetRel(it.states[state], project);
  };
  const hasBorder = node => (node.slice || []).some(v => v > 0);

  const L = [];
  L.push('System.Action<UnityEngine.GameObject, float, float, float, float> __stretchChild = (go, l, b, r, t) => {');
  L.push('  var rt = go.GetComponent<UnityEngine.RectTransform>();');
  L.push('  rt.anchorMin = UnityEngine.Vector2.zero; rt.anchorMax = UnityEngine.Vector2.one;');
  L.push('  rt.offsetMin = new UnityEngine.Vector2(l, b); rt.offsetMax = new UnityEngine.Vector2(-r, -t);');
  L.push('};');
  L.push(`// generated by unity-ugui/build.js — spec ${q(spec.name)}`);
  L.push(`var __old = UnityEngine.GameObject.Find("${q(rootName)}");`);
  L.push('if (__old != null) UnityEngine.Object.DestroyImmediate(__old);');
  L.push(`var __root = new UnityEngine.GameObject("${q(rootName)}", typeof(UnityEngine.RectTransform), typeof(UnityEngine.Canvas), typeof(UnityEngine.UI.CanvasScaler), typeof(UnityEngine.UI.GraphicRaycaster));`);
  L.push('var __canvas = __root.GetComponent<UnityEngine.Canvas>();');
  L.push('__canvas.renderMode = UnityEngine.RenderMode.ScreenSpaceOverlay;');
  L.push(`__canvas.sortingOrder = ${spec.canvas.sorting_order || 0};`);
  L.push('var __scaler = __root.GetComponent<UnityEngine.UI.CanvasScaler>();');
  L.push('__scaler.uiScaleMode = UnityEngine.UI.CanvasScaler.ScaleMode.ScaleWithScreenSize;');
  L.push(`__scaler.referenceResolution = new UnityEngine.Vector2(${spec.canvas.reference_resolution[0].toFixed(1)}f, ${spec.canvas.reference_resolution[1].toFixed(1)}f);`);
  L.push(`__scaler.screenMatchMode = UnityEngine.UI.CanvasScaler.ScreenMatchMode.MatchWidthOrHeight;`);
  L.push(`__scaler.matchWidthOrHeight = ${Number(spec.canvas.match).toFixed(3)}f;`);
  L.push('var __es = UnityEngine.Object.FindObjectOfType<UnityEngine.EventSystems.EventSystem>();');
  L.push('if (__es == null) { var __esGo = new UnityEngine.GameObject("EventSystem", typeof(UnityEngine.EventSystems.EventSystem), typeof(UnityEngine.EventSystems.StandaloneInputModule)); __esGo.transform.SetParent(__root.transform, false); }');
  L.push('var __map = new System.Collections.Generic.Dictionary<string, UnityEngine.GameObject>();');
  L.push('__map["__root__"] = __root;');
  L.push('System.Func<string, UnityEngine.Sprite> __sprite = (rel) => UnityEditor.AssetDatabase.LoadAssetAtPath<UnityEngine.Sprite>(rel);');
  // 内置 Arial 不含中文字形：按 OS 字体名优先取中文字体，失败才回退 Arial。
  // 不写绝对路径（技能要求可搬运），也不依赖某台机器上的字体文件位置。
  const fontNames = (spec.palette && spec.palette.font_family) ||
    ['Microsoft YaHei UI', 'Microsoft YaHei', 'SimHei', 'Arial'];
  const fontLit = fontNames.map(f => `"${q(f)}"`).join(', ');
  L.push(`var __uiFont = UnityEngine.Font.CreateDynamicFontFromOSFont(new string[] { ${fontLit} }, 32);`);
  L.push('if (__uiFont == null) __uiFont = UnityEngine.Resources.GetBuiltinResource<UnityEngine.Font>("Arial.ttf");');
  L.push('System.Action<UnityEngine.GameObject, float[]> __setRect = (go, v) => {');
  L.push('  var rt = go.GetComponent<UnityEngine.RectTransform>();');
  L.push('  rt.anchorMin = new UnityEngine.Vector2(v[0], v[1]);');
  L.push('  rt.anchorMax = new UnityEngine.Vector2(v[2], v[3]);');
  L.push('  rt.pivot = new UnityEngine.Vector2(v[4], v[5]);');
  L.push('  rt.anchoredPosition = new UnityEngine.Vector2(v[6], v[7]);');
  L.push('  rt.sizeDelta = new UnityEngine.Vector2(v[8], v[9]);');
  L.push('  if (v[10] > 0.5f) { rt.offsetMin = new UnityEngine.Vector2(v[11], v[12]); rt.offsetMax = new UnityEngine.Vector2(v[13], v[14]); }');
  L.push('};');
  L.push('System.Func<UnityEngine.GameObject, string, int, UnityEngine.Color, string, UnityEngine.UI.Text> __text = (parent, txt, size, col, align) => {');
  L.push('  var tgo = new UnityEngine.GameObject("Text", typeof(UnityEngine.RectTransform));');
  L.push('  tgo.transform.SetParent(parent.transform, false);');
  L.push('  var trt = tgo.GetComponent<UnityEngine.RectTransform>();');
  L.push('  trt.anchorMin = UnityEngine.Vector2.zero; trt.anchorMax = UnityEngine.Vector2.one;');
  L.push('  trt.offsetMin = UnityEngine.Vector2.zero; trt.offsetMax = UnityEngine.Vector2.zero;');
  L.push('  var t = tgo.AddComponent<UnityEngine.UI.Text>();');
  L.push('  t.font = __uiFont;');
  L.push('  t.text = txt; t.fontSize = size; t.color = col;');
  L.push('  t.alignment = (UnityEngine.TextAnchor)System.Enum.Parse(typeof(UnityEngine.TextAnchor), align);');
  L.push('  t.raycastTarget = false;');
  L.push('  return t;');
  L.push('};');

  // 按 depth 升序、order 升序，保证父节点先建
  const nodes = spec.nodes.slice().sort((a, b) => (a.depth - b.depth) || (a.order - b.order));
  // SetSiblingIndex 是**同父内的局部序号**，不能直接用全局 order：
  // 一旦 Spec 有 parent 分组，全局 order 会越界并被 Unity clamp 到末尾，绘制顺序就会乱。
  const siblingSeq = {};
  for (const n of nodes) {
    const d = controls.def(n.type);
    if (!d || n.type === 'canvas') continue;
    const v = `v_${n.id.replace(/[^A-Za-z0-9_]/g, '_')}`;
    const parentKey = n.parent || '__root__';
    L.push(`var ${v} = new UnityEngine.GameObject("${q(n.name || n.id)}", typeof(UnityEngine.RectTransform));`);
    L.push(`${v}.transform.SetParent(__map["${q(parentKey)}"].transform, false);`);
    const localIndex = siblingSeq[parentKey] || 0;
    siblingSeq[parentKey] = localIndex + 1;
    L.push(`${v}.transform.SetSiblingIndex(${localIndex});`);
    L.push(`__map["${q(n.id)}"] = ${v};`);
    L.push(`__setRect(${v}, ${csArray(rectValues(n, spec))});`);
    if (n.visible === false) L.push(`${v}.SetActive(false);`);

    const rel = relOf(n.id);
    const needImage = d.ugui && d.ugui.includes('Image');
    const needText = d.needsText;
    const col = csColor(n.color || spec.palette.on_surface);
    const align = TEXT_ANCHORS[(n.style && n.style.text_align) || 'middle_center'] || 'MiddleCenter';
    const fontSize = n.font_size || spec.palette.font_size || 24;

    if (needImage) {
      L.push(`var __img_${v} = ${v}.AddComponent<UnityEngine.UI.Image>();`);
      if (rel) L.push(`__img_${v}.sprite = __sprite("${q(rel)}");`);
      else if (n.asset !== 'none') L.push(`__img_${v}.color = ${csColor((n.style && n.style.background) || spec.palette.surface)};`);
      if (hasBorder(n) && rel) L.push(`__img_${v}.type = UnityEngine.UI.Image.Type.Sliced;`);
      if (n.type === 'progress') {
        L.push(`__img_${v}.type = UnityEngine.UI.Image.Type.Filled;`);
        L.push(`__img_${v}.fillMethod = UnityEngine.UI.Image.FillMethod.Horizontal;`);
        L.push(`__img_${v}.fillAmount = ${Number(n.value === undefined ? 1 : n.value).toFixed(3)}f;`);
      }
      L.push(`__img_${v}.raycastTarget = ${d.interactive ? 'true' : 'false'};`);
    }

    switch (n.type) {
      case 'label': {
        L.push(`var __t_${v} = ${v}.AddComponent<UnityEngine.UI.Text>();`);
        L.push(`__t_${v}.font = __uiFont;`);
        L.push(`__t_${v}.text = "${q(n.text)}"; __t_${v}.fontSize = ${fontSize}; __t_${v}.color = ${col};`);
        L.push(`__t_${v}.alignment = UnityEngine.TextAnchor.${align}; __t_${v}.raycastTarget = false;`);
        break;
      }
      case 'button': {
        L.push(`var __btn_${v} = ${v}.AddComponent<UnityEngine.UI.Button>();`);
        L.push(`__btn_${v}.targetGraphic = __img_${v};`);
        const hover = stateRel(n, 'hover'), pressed = stateRel(n, 'pressed'), disabled = stateRel(n, 'disabled');
        if (hover || pressed || disabled) {
          L.push(`__btn_${v}.transition = UnityEngine.UI.Selectable.Transition.SpriteSwap;`);
          L.push(`var __ss_${v} = new UnityEngine.UI.SpriteState();`);
          if (hover) L.push(`__ss_${v}.highlightedSprite = __sprite("${q(hover)}");`);
          if (pressed) L.push(`__ss_${v}.pressedSprite = __sprite("${q(pressed)}");`);
          if (disabled) L.push(`__ss_${v}.disabledSprite = __sprite("${q(disabled)}");`);
          L.push(`__btn_${v}.spriteState = __ss_${v};`);
        }
        L.push(`__text(${v}, "${q(n.text)}", ${fontSize}, ${col}, "${align}");`);
        break;
      }
      case 'toggle':
      case 'tab': {
        L.push(`var __tgl_${v} = ${v}.AddComponent<UnityEngine.UI.Toggle>();`);
        L.push(`__tgl_${v}.targetGraphic = __img_${v};`);
        L.push(`var __ckGo_${v} = new UnityEngine.GameObject("Checkmark", typeof(UnityEngine.RectTransform));`);
        L.push(`__ckGo_${v}.transform.SetParent(${v}.transform, false);`);
        L.push(`var __ckRt_${v} = __ckGo_${v}.GetComponent<UnityEngine.RectTransform>();`);
        L.push(`__ckRt_${v}.anchorMin = UnityEngine.Vector2.zero; __ckRt_${v}.anchorMax = UnityEngine.Vector2.one;`);
        L.push(`__ckRt_${v}.offsetMin = UnityEngine.Vector2.zero; __ckRt_${v}.offsetMax = UnityEngine.Vector2.zero;`);
        L.push(`var __ck_${v} = __ckGo_${v}.AddComponent<UnityEngine.UI.Image>();`);
        const ckSpr = stateRel(n, 'checked') || rel;
        if (ckSpr) L.push(`__ck_${v}.sprite = __sprite("${q(ckSpr)}");`);
        L.push(`__ck_${v}.raycastTarget = false;`);
        L.push(`__tgl_${v}.graphic = __ck_${v};`);
        L.push(`__tgl_${v}.isOn = ${n.checked ? 'true' : 'false'};`);
        if (n.text) L.push(`__text(${v}, "${q(n.text)}", ${fontSize}, ${col}, "${align}");`);
        break;
      }
      case 'slider': {
        L.push(`var __sld_${v} = ${v}.AddComponent<UnityEngine.UI.Slider>();`);
        L.push(`var __bg_${v} = ${v}.AddComponent<UnityEngine.UI.Image>();`);
        if (rel) L.push(`__bg_${v}.sprite = __sprite("${q(rel)}");`);
        L.push(`__sld_${v}.targetGraphic = __bg_${v};`);
        // Fill Area / Fill
        L.push(`var __faGo_${v} = new UnityEngine.GameObject("Fill Area", typeof(UnityEngine.RectTransform));`);
        L.push(`__faGo_${v}.transform.SetParent(${v}.transform, false);`);
        L.push(`__stretchChild(__faGo_${v}, 0f, 0f, -10f, -10f);`);
        L.push(`var __fillGo_${v} = new UnityEngine.GameObject("Fill", typeof(UnityEngine.RectTransform));`);
        L.push(`__fillGo_${v}.transform.SetParent(__faGo_${v}.transform, false);`);
        L.push(`__stretchChild(__fillGo_${v}, 0f, 0f, 0f, 0f);`);
        L.push(`var __fillImg_${v} = __fillGo_${v}.AddComponent<UnityEngine.UI.Image>();`);
        if (stateRel(n, 'checked')) L.push(`__fillImg_${v}.sprite = __sprite("${q(stateRel(n, 'checked'))}");`);
        L.push(`__sld_${v}.fillRect = __fillImg_${v}.rectTransform;`);
        // Handle Slide Area / Handle
        L.push(`var __haGo_${v} = new UnityEngine.GameObject("Handle Slide Area", typeof(UnityEngine.RectTransform));`);
        L.push(`__haGo_${v}.transform.SetParent(${v}.transform, false);`);
        L.push(`__stretchChild(__haGo_${v}, 0f, 0f, 0f, 0f);`);
        L.push(`var __hGo_${v} = new UnityEngine.GameObject("Handle", typeof(UnityEngine.RectTransform));`);
        L.push(`__hGo_${v}.transform.SetParent(__haGo_${v}.transform, false);`);
        L.push(`var __hRt_${v} = __hGo_${v}.GetComponent<UnityEngine.RectTransform>();`);
        L.push(`__hRt_${v}.sizeDelta = new UnityEngine.Vector2(20f, 0f);`);
        L.push(`__hRt_${v}.anchorMin = new UnityEngine.Vector2(0f, 0f); __hRt_${v}.anchorMax = new UnityEngine.Vector2(0f, 1f);`);
        L.push(`var __hImg_${v} = __hGo_${v}.AddComponent<UnityEngine.UI.Image>();`);
        L.push(`__sld_${v}.handleRect = __hImg_${v}.rectTransform;`);
        L.push(`__sld_${v}.targetGraphic = __hImg_${v};`);
        L.push(`__sld_${v}.direction = UnityEngine.UI.Slider.Direction.LeftToRight;`);
        L.push(`__sld_${v}.minValue = 0f; __sld_${v}.maxValue = 1f; __sld_${v}.value = ${Number(n.value === undefined ? 0.5 : n.value).toFixed(3)}f;`);
        break;
      }
      case 'input': {
        L.push(`var __inp_${v} = ${v}.AddComponent<UnityEngine.UI.InputField>();`);
        L.push(`__inp_${v}.targetGraphic = __img_${v};`);
        L.push(`var __tx_${v} = __text(${v}, "${q(n.text)}", ${fontSize}, ${col}, "MiddleLeft");`);
        L.push(`var __ph_${v} = __text(${v}, "${q((n.style && n.style.placeholder) || '')}", ${fontSize}, ${csColor(spec.palette.border)}, "MiddleLeft");`);
        L.push(`__inp_${v}.textComponent = __tx_${v};`);
        L.push(`__inp_${v}.placeholder = __ph_${v};`);
        break;
      }
      case 'scroll': {
        L.push(`var __sr_${v} = ${v}.AddComponent<UnityEngine.UI.ScrollRect>();`);
        L.push(`var __vpGo_${v} = new UnityEngine.GameObject("Viewport", typeof(UnityEngine.RectTransform));`);
        L.push(`__vpGo_${v}.transform.SetParent(${v}.transform, false);`);
        L.push(`__stretchChild(__vpGo_${v}, 0f, 0f, 0f, 0f);`);
        L.push(`__vpGo_${v}.AddComponent<UnityEngine.UI.RectMask2D>();`);
        L.push(`var __ctGo_${v} = new UnityEngine.GameObject("Content", typeof(UnityEngine.RectTransform));`);
        L.push(`__ctGo_${v}.transform.SetParent(__vpGo_${v}.transform, false);`);
        L.push(`var __ctRt_${v} = __ctGo_${v}.GetComponent<UnityEngine.RectTransform>();`);
        L.push(`__ctRt_${v}.anchorMin = new UnityEngine.Vector2(0f, 1f); __ctRt_${v}.anchorMax = new UnityEngine.Vector2(1f, 1f);`);
        L.push(`__ctRt_${v}.pivot = new UnityEngine.Vector2(0.5f, 1f); __ctRt_${v}.sizeDelta = new UnityEngine.Vector2(0f, 0f);`);
        L.push(`__sr_${v}.viewport = __vpGo_${v}.GetComponent<UnityEngine.RectTransform>();`);
        L.push(`__sr_${v}.content = __ctRt_${v};`);
        L.push(`__sr_${v}.horizontal = false; __sr_${v}.vertical = true;`);
        break;
      }
      case 'dropdown': {
        L.push(`var __dd_${v} = ${v}.AddComponent<UnityEngine.UI.Dropdown>();`);
        L.push(`__dd_${v}.targetGraphic = __img_${v};`);
        L.push(`var __cap_${v} = __text(${v}, "${q(n.text || ((n.items || [])[0] || ''))}", ${fontSize}, ${col}, "MiddleLeft");`);
        L.push(`__dd_${v}.captionText = __cap_${v};`);
        L.push(`var __tplGo_${v} = new UnityEngine.GameObject("Template", typeof(UnityEngine.RectTransform));`);
        L.push(`__tplGo_${v}.transform.SetParent(${v}.transform, false);`);
        L.push(`__stretchChild(__tplGo_${v}, 0f, 0f, 0f, 0f);`);
        L.push(`var __item_${v} = __text(__tplGo_${v}, "Option", ${fontSize}, ${col}, "MiddleLeft");`);
        L.push(`var __itemImg_${v} = __tplGo_${v}.AddComponent<UnityEngine.UI.Image>();`);
        L.push(`__dd_${v}.itemText = __item_${v};`);
        L.push(`__dd_${v}.template = __tplGo_${v}.GetComponent<UnityEngine.RectTransform>();`);
        L.push(`__dd_${v}.options.Clear();`);
        (n.items || []).forEach(it => L.push(`__dd_${v}.options.Add(new UnityEngine.UI.Dropdown.OptionData("${q(it)}"));`));
        L.push(`__tplGo_${v}.SetActive(false);`);
        break;
      }
      case 'badge': {
        if (n.text) L.push(`__text(${v}, "${q(n.text)}", ${fontSize}, ${col}, "${align}");`);
        break;
      }
      default: break;
    }
  }

  L.push('UnityEditor.AssetDatabase.SaveAssets();');
  if (o.saveScene !== false) {
    L.push('UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(UnityEngine.SceneManagement.SceneManager.GetActiveScene());');
    L.push('UnityEditor.SceneManagement.EditorSceneManager.SaveScene(UnityEngine.SceneManagement.SceneManager.GetActiveScene());');
  }
  L.push(`UnityEngine.Debug.Log("[unity-ugui] built ${q(rootName)} with ${nodes.length} nodes");`);
  return L.join('\n');
}

async function build(spec, manifest, o = {}) {
  const code = generateCSharp(spec, manifest, o);
  // 本地静态预检：复用 mcp 的 C#5 lint，挡在提交前
  mcp.assertLint(code);
  const r = await mcp.call('code.execute', {
    mode: 'runtime', code,
    description: `Build UGUI hierarchy from spec ${spec.name}`,
    includes: ['UnityEditor', 'UnityEngine', 'UnityEngine.UI', 'UnityEngine.EventSystems', 'System.Collections.Generic'],
    return_output: true,
    timeout: 180,
  });
  return { ok: true, result: r, code, nodeCount: spec.nodes.length };
}

/** 降级：用 demo 的 ugui.create_component 逐个建（控件残缺，verify 会报）。 */
async function buildViaModule(spec, o = {}) {
  const warnings = [];
  const calls = [];
  for (const n of spec.nodes.slice().sort((a, b) => (a.depth - b.depth) || (a.order - b.order))) {
    const comp = controls.TO_MODULE[n.type];
    if (!comp) { warnings.push(`${n.id}(${n.type}) 无法用 create_component 表达，已跳过`); continue; }
    calls.push(await mcp.call('ugui.create_component', { component: comp, name: n.name || n.id }));
  }
  warnings.push('已走降级路径：Slider/Toggle/InputField 无真实组件绑定，ScrollRect/Dropdown 缺失；请切换到 code 路径重建');
  return { ok: true, calls, warnings, nodeCount: calls.length };
}

